def build_moves(chart, date_str):
    try:
        i = chart['dates'].index(date_str)
    except ValueError:
        return {}
    if i == 0:
        return {}
    out = {}
    for key, label in MOVE_SYMBOLS:
        s = chart.get(key)
        if not s or i >= len(s) or not s[i - 1]:
            continue
        out[label] = round((s[i] - s[i - 1]) / s[i - 1] * 100, 2)
    return out


def main():
    dry = '--dry' in sys.argv
    with open(EVENTS, encoding='utf-8') as f:
        events = json.load(f)
    with open(CHART, encoding='utf-8') as f:
        chart = json.load(f)

    have = {e['date'] for e in events}
    added, skipped, nochart = [], [], []
    for date, (title, groups) in sorted(SEED.items()):
        if date in have:
            skipped.append(date)
            continue
        moves = build_moves(chart, date)
        if not moves:
            nochart.append(date)
            continue
        events.append({
            'date': date,
            'title': title,
            'importance': 2,
            'moves': moves,
            'summaryGroups': [
                {'heading': h, 'tone': t, 'cat': c, 'points': p} for h, t, c, p in groups
            ],
            'cats': sorted({c for _, _, c, _ in groups}),
            'link': None,
            'source': 'external_knowledge',
        })
        added.append(date)

    events.sort(key=lambda e: e['date'])
    print(f'추가 {len(added)}일 · 이미 있어 건너뜀 {len(skipped)} · 차트에 없는 날짜 {len(nochart)}')
    if nochart:
        print('  차트 미보유:', ', '.join(nochart))
    if dry:
        print('--dry — 파일을 쓰지 않았다')
        return 0
    with open(EVENTS, 'w', encoding='utf-8') as f:
        json.dump(events, f, ensure_ascii=False, indent=1)
    return 0


if __name__ == '__main__':
    sys.exit(main())
